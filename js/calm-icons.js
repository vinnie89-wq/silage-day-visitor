(function () {
  // One pattern that finds any of the emojis above (with or without
  // the invisible "show as emoji" character U+FE0F after it)
  const keys = Object.keys(CALM_ICONS);
  const pattern = new RegExp("(" + keys.join("|") + ")️?", "gu");
  const SKIP = { SCRIPT: 1, STYLE: 1, TITLE: 1, TEXTAREA: 1, OPTION: 1, NOSCRIPT: 1 };

  function svgFor(emoji) {
    return '<svg class="lu" viewBox="0 0 24 24" aria-hidden="true" focusable="false" fill="none" ' +
      'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' +
      CALM_ICONS[emoji] + '</svg>';
  }

  function decorateText(node) {
    const text = node.nodeValue;
    pattern.lastIndex = 0;
    if (!text || !pattern.test(text)) return;
    const parent = node.parentNode;
    if (!parent || parent.nodeType !== 1 || SKIP[parent.nodeName] || parent.closest(".emo-pair")) return;
    pattern.lastIndex = 0;
    const holder = document.createElement("span");
    holder.innerHTML = text
      .replace(/&/g, "&amp;").replace(/</g, "&lt;")
      .replace(pattern, function (whole, emoji) {
        return '<span class="emo-pair"><span class="emo">' + whole + '</span>' + svgFor(emoji) + '</span>';
      });
    const bits = document.createDocumentFragment();
    while (holder.firstChild) bits.appendChild(holder.firstChild);
    parent.replaceChild(bits, node);
  }

  function decorate(root) {
    if (root.nodeType === 3) { decorateText(root); return; }
    if (root.nodeType !== 1 || SKIP[root.nodeName] || root.closest(".emo-pair")) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const found = [];
    while (walker.nextNode()) found.push(walker.currentNode);
    found.forEach(decorateText);
  }

  // Watch from the very start, so emojis are paired as the page is
  // read in: no flash of colourful emojis for calm-mode visitors.
  const watcher = new MutationObserver(function (changes) {
    changes.forEach(function (change) {
      change.addedNodes.forEach(decorate);
      if (change.type === "characterData") decorateText(change.target);
    });
  });
  watcher.observe(document.documentElement, { childList: true, subtree: true, characterData: true });
  document.addEventListener("DOMContentLoaded", function () { decorate(document.body); });
})();
